// Width in pixels of a string at scale s (5 px glyph + 1 px gap).
export function textWidth(str, s = 1) {
  return str.length * 6 * s - s;
}

// Calls plot(x, y) for every lit pixel of str, top-left at (x0, y0).
export function drawText(str, x0, y0, s, plot) {
  let x = x0;
  for (const ch of str.toUpperCase()) {
    const g = G[ch] ?? G["#"];
    for (let i = 0; i < 35; i++) {
      if (g[i] !== "#") continue;
      const gx = x + (i % 5) * s, gy = y0 + Math.floor(i / 5) * s;
      for (let dy = 0; dy < s; dy++) for (let dx = 0; dx < s; dx++) plot(gx + dx, gy + dy);
    }
    x += 6 * s;
  }
}
